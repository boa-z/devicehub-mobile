type I18nContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: keyof typeof en, params?: TranslationParams) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

function interpolate(value: string, params?: TranslationParams) {
  if (!params) return value;
  return value.replace(/\{(\w+)\}/g, (match, key: string) => {
    const replacement = params[key];
    return replacement === undefined ? match : String(replacement);
  });
}

export function I18nProvider({ children }: PropsWithChildren) {
  const [language, setLanguageState] = useState<Language>("en");

  useEffect(() => {
    let active = true;
    void loadSavedLanguage().then((saved) => {
      if (active) setLanguageState(saved);
    });
    return () => {
      active = false;
    };
  }, []);

  const setLanguage = (next: Language) => {
    setLanguageState(next);
    void saveLanguage(next).catch(() => undefined);
  };

  const value = useMemo<I18nContextValue>(() => ({
    language,
    setLanguage,
    t: (key, params) => interpolate((language === "zh" ? zh : en)[key], params),
  }), [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}

